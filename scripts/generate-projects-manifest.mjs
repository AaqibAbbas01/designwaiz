import { promises as fs } from "node:fs";
import path from "node:path";

const PROJECT_FOLDERS = [
  "ATS 5202",
  "Akhil ji",
  "Ambala Site Picx",
  "Apex 2802",
  "Bharat Gaur Homes",
  "Facade & Others",
  "Meerut Sheel Kunj",
  "More Projects",
  "Sec.70 Images",
  "Tricolor Office",
  "Vasant Vihar F 39",
];

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png"]);
const VIDEO_EXTENSIONS = new Set([".mp4", ".mov"]);
const HEIC_EXTENSIONS = new Set([".heic"]);
const IGNORED_FILES = new Set([".ds_store"]);

const rootDir = process.cwd();
const publicDir = path.join(rootDir, "public", "waseem2");
const outputDir = path.join(rootDir, "src", "lib", "generated");
const outputFile = path.join(outputDir, "projects-manifest.ts");

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^\w-]+/g, "")
    .replace(/--+/g, "-")
    .trim();
}

function publicSrc(folderName, fileName) {
  return `/waseem2/${folderName}/${fileName}`;
}

function convertedNameForHeic(fileName) {
  return fileName.replace(/\.[^.]+$/, ".converted.jpg");
}

function isConvertedHeicJpg(fileName) {
  return fileName.toLowerCase().endsWith(".converted.jpg");
}

function sortFiles(fileNames) {
  return [...fileNames].sort((a, b) =>
    a.localeCompare(b, undefined, {
      numeric: true,
      sensitivity: "base",
    })
  );
}

async function readProjectFolder(folderName, index) {
  const folderPath = path.join(publicDir, folderName);
  const dirEntries = await fs.readdir(folderPath, { withFileTypes: true });
  const fileNames = sortFiles(
    dirEntries
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
      .filter((name) => !IGNORED_FILES.has(name.toLowerCase()))
  );

  const fileSet = new Set(fileNames);
  const slug = slugify(folderName);
  const label = `Project ${index + 1}`;

  const mediaDrafts = fileNames.flatMap((fileName) => {
    const ext = path.extname(fileName).toLowerCase();

    if (HEIC_EXTENSIONS.has(ext)) {
      const convertedName = convertedNameForHeic(fileName);
      if (!fileSet.has(convertedName)) {
        return [];
      }

      return [{ src: publicSrc(folderName, convertedName), type: "image" }];
    }

    if (isConvertedHeicJpg(fileName)) {
      const baseName = fileName.replace(/\.converted\.jpg$/i, "");
      if (fileSet.has(`${baseName}.HEIC`) || fileSet.has(`${baseName}.heic`)) {
        return [];
      }
    }

    if (IMAGE_EXTENSIONS.has(ext)) {
      return [{ src: publicSrc(folderName, fileName), type: "image" }];
    }

    if (VIDEO_EXTENSIONS.has(ext)) {
      return [{ src: publicSrc(folderName, fileName), type: "video" }];
    }

    return [];
  });

  let imageNumber = 0;
  let videoNumber = 0;

  const media = mediaDrafts.map((item, mediaIndex) => {
    if (item.type === "image") {
      imageNumber += 1;
    } else {
      videoNumber += 1;
    }

    const typeNumber = item.type === "image" ? imageNumber : videoNumber;

    return {
      id: `${slug}-${mediaIndex + 1}`,
      src: item.src,
      type: item.type,
      projectSlug: slug,
      projectLabel: label,
      alt: `${label} ${item.type} ${typeNumber}`,
    };
  });

  const coverImage = media.find((item) => item.type === "image")?.src ?? media[0]?.src ?? "";
  const photoCount = media.filter((item) => item.type === "image").length;
  const videoCount = media.filter((item) => item.type === "video").length;

  return {
    folderName,
    slug,
    label,
    href: `/projects/${slug}`,
    coverImage,
    photoCount,
    videoCount,
    totalMedia: media.length,
    media,
  };
}

async function main() {
  const projects = await Promise.all(PROJECT_FOLDERS.map((folderName, index) => readProjectFolder(folderName, index)));
  const fileContents = `// This file is auto-generated by scripts/generate-projects-manifest.mjs\n` +
    `// Do not edit manually.\n\n` +
    `export const PROJECTS_MANIFEST = ${JSON.stringify(projects, null, 2)} as const;\n`;

  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(outputFile, fileContents);
  console.log(`Generated ${path.relative(rootDir, outputFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
